"""
diagnose_losing_years.py — what drives the loss in 2013, 2019, 2022, 2025?

Uses results/all_transitions_summary.csv (271 transitions) and
results/per_window_all_115_summary.csv (115 recovery windows) — already
generated by earlier diagnostic runs — to decompose the bleed in each
losing year into discrete failure modes.

Failure modes:
  (A) False defensive   — went FLAT/SHORT/GOLD but NIFTY rose ≥2% next 20d
                          → strategy was over-defensive
  (B) False risk-on     — went LONG but Mom30 fell ≥2% next 20d
                          → strategy entered too early / wrong signal
  (C) Late re-entry     — went LONG AFTER NIFTY already rallied (high f20 negative)
                          → strategy got back in after the move
  (D) Mom30 asset lag   — Mom30 underperformed NIFTY ≥3pp during recovery window
                          → asset choice wrong (not a signal problem)
  (E) Whipsaw / chop    — many transitions in a short window (≥3 in 30 days)
                          → entry-lag accumulates

For each year we tabulate which modes are present and how costly each was.
"""

import os
import pandas as pd
import numpy as np

RESULTS_DIR = os.path.normpath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "results"))

trans = pd.read_csv(os.path.join(RESULTS_DIR, "all_transitions_summary.csv"),
                    parse_dates=["date"])
windows = pd.read_csv(os.path.join(RESULTS_DIR, "per_window_all_115_summary.csv"),
                      parse_dates=["re_entry", "stretch_start"])

# Cost of each transition (in pp). Defensive → cost = NIFTY 20d fwd if we missed rally.
def cost_pp(row):
    f_n = row.get("f20_n"); f_s = row.get("f20_strat"); f_m = row.get("f20_m")
    f_n = float(f_n) if pd.notna(f_n) else 0
    f_s = float(f_s) if pd.notna(f_s) else 0
    f_m = float(f_m) if pd.notna(f_m) else 0
    if row["from"] in ("LONG", "LONG_V2") and row["to"] in ("FLAT", "SHORT", "GOLD"):
        return f_n - f_s
    if row["from"] in ("FLAT", "SHORT", "GOLD") and row["to"] in ("LONG", "LONG_V2"):
        return -f_s
    if row["to"] == "SHORT":
        return 2 * f_n
    return 0.0

trans["cost_pp"] = trans.apply(cost_pp, axis=1)

# ---- Failure mode classification per transition --------------------------
def classify(row):
    """Returns the dominant failure mode tag(s) for a single transition."""
    tags = []
    f_n = float(row["f20_n"]) if pd.notna(row["f20_n"]) else 0
    f_m = float(row["f20_m"]) if pd.notna(row["f20_m"]) else 0
    is_def = row["from"] in ("LONG", "LONG_V2") and row["to"] in ("FLAT", "SHORT", "GOLD")
    is_risk_on = row["from"] in ("FLAT", "SHORT", "GOLD") and row["to"] in ("LONG", "LONG_V2")
    is_false = row["verdict"].startswith("FALSE")
    if is_def and is_false:
        tags.append("A-false-def")     # went flat but NIFTY rose
    if is_risk_on and is_false and f_m < -0.02:
        tags.append("B-false-on")      # went long but Mom30 fell
    if is_risk_on and row["verdict"].startswith("NEUTRAL") and f_n < -0.01:
        tags.append("C-late-reentry")  # entered after NIFTY peaked
    return tags

trans["modes"] = trans.apply(classify, axis=1)

# ---- Build per-year reports ----------------------------------------------
YEARS = [2013, 2019, 2022, 2025]
out = []
def p(text=""): print(text); out.append(text)

p("=" * 130)
p("  LOSING YEARS DIAGNOSIS — 2013, 2019, 2022, 2025")
p("=" * 130)
p()
p("  Source: results/all_transitions_summary.csv (271 transitions across 2008-2025)")
p("           results/per_window_all_115_summary.csv (115 recovery windows)")
p("  NOTE: these files were generated for the C1 baseline (V2 only, no 5d lock).")
p("        The L5 lock blocks ~30% of slow-stress fires; net effect on 2013/2019")
p("        is the year-level improvement, but underlying transition data here")
p("        still shows the unsuppressed signal mechanics.")
p()

# Year-level summary
p("=" * 130)
p("  YEAR-LEVEL TRANSITION SUMMARY")
p("=" * 130)
p(f"  {'Year':<6} {'Total':>6} {'WORKED':>8} {'NEUTRAL':>9} {'FALSE':>8} {'Net cost (pp)':>15} {'Mom30 lag windows':>20}")
p("  " + "-"*6 + " " + "-"*6 + " " + "-"*8 + " " + "-"*9 + " " + "-"*8 + " " + "-"*15 + " " + "-"*20)
for y in YEARS:
    yt = trans[trans["year"] == y]
    wd = yt["verdict"].apply(lambda s: s.split(" ")[0]).value_counts()
    worked = int(wd.get("WORKED", 0))
    neutral = int(wd.get("NEUTRAL", 0))
    false = int(wd.get("FALSE", 0))
    total = len(yt)
    net_cost = yt["cost_pp"].sum() * 100
    yw = windows[windows["year"] == y]
    lag = yw[(yw["winner"] != "Mom30") &
             ((yw["cum_m_pct"] - yw["winner_ret_pct"]) < -0.03)]
    p(f"  {y:<6} {total:>6d} {worked:>8d} {neutral:>9d} {false:>8d} {net_cost:>+13.2f}pp {len(lag):>11d} of {len(yw)} windows")
p()

# Per-year deep dive
for y in YEARS:
    p("=" * 130)
    p(f"  {y} — DEEP DIVE")
    p("=" * 130)
    yt = trans[trans["year"] == y].copy().sort_values("cost_pp", ascending=False)
    yw = windows[windows["year"] == y]

    # Mode counts
    def_false = [r for _, r in yt.iterrows() if "A-false-def" in r["modes"]]
    risk_false = [r for _, r in yt.iterrows() if "B-false-on" in r["modes"]]
    late_reentry = [r for _, r in yt.iterrows() if "C-late-reentry" in r["modes"]]

    p(f"  Transitions: {len(yt)} total  ({len([r for _, r in yt.iterrows() if r['verdict'].startswith('FALSE')])} FALSE)")
    p(f"  Recovery windows: {len(yw)}")
    p()

    # (A) False defensive
    p(f"  (A) FALSE DEFENSIVE — went FLAT/SHORT/GOLD when NIFTY then rallied: {len(def_false)} transitions")
    if def_false:
        sum_cost = sum(float(r['cost_pp']) for r in def_false) * 100
        p(f"      Total cost: {sum_cost:+.2f}pp")
        for r in def_false[:5]:
            p(f"        {r['date'].strftime('%Y-%m-%d')}: {r['from']} → {r['to']} via {r['cause']}, "
              f"NIFTY 20d fwd {float(r['f20_n'])*100:+.1f}%, cost {float(r['cost_pp'])*100:+.2f}pp")
    p()

    # (B) False risk-on
    p(f"  (B) FALSE RISK-ON — entered LONG but Mom30 fell next 20d: {len(risk_false)} transitions")
    if risk_false:
        sum_cost = sum(float(r['cost_pp']) for r in risk_false) * 100
        p(f"      Total cost: {sum_cost:+.2f}pp")
        for r in risk_false[:5]:
            p(f"        {r['date'].strftime('%Y-%m-%d')}: {r['from']} → {r['to']} via {r['cause']}, "
              f"Mom30 20d fwd {float(r['f20_m'])*100:+.1f}%, cost {float(r['cost_pp'])*100:+.2f}pp")
    p()

    # (C) Late re-entry
    p(f"  (C) LATE RE-ENTRY — re-entered LONG after NIFTY had already peaked: {len(late_reentry)} transitions")
    if late_reentry:
        sum_cost = sum(float(r['cost_pp']) for r in late_reentry) * 100
        p(f"      Total cost: {sum_cost:+.2f}pp")
        for r in late_reentry[:3]:
            p(f"        {r['date'].strftime('%Y-%m-%d')}: NIFTY 20d fwd {float(r['f20_n'])*100:+.1f}%, "
              f"cost {float(r['cost_pp'])*100:+.2f}pp")
    p()

    # (D) Mom30 asset lag — from recovery windows
    mom_lag_wins = yw[(yw["winner"] != "Mom30") &
                      ((yw["cum_m_pct"] - yw["winner_ret_pct"]) < -0.03)]
    p(f"  (D) MOM30 ASSET LAG — recovery windows where Mom30 lagged winner by ≥3pp: "
      f"{len(mom_lag_wins)} of {len(yw)} windows")
    if len(mom_lag_wins):
        total_lag = (mom_lag_wins["cum_m_pct"] - mom_lag_wins["winner_ret_pct"]).sum() * 100
        p(f"      Total Mom30 underperformance: {total_lag:+.2f}pp")
        for _, r in mom_lag_wins.iterrows():
            diff = (float(r["cum_m_pct"]) - float(r["winner_ret_pct"])) * 100
            p(f"        {r['re_entry'].strftime('%Y-%m-%d')}: winner={r['winner']} "
              f"({float(r['winner_ret_pct'])*100:+.1f}%), Mom30={float(r['cum_m_pct'])*100:+.1f}% "
              f"→ {diff:+.1f}pp behind")
    p()

    # (E) Whipsaw / chop — count clusters of 3+ transitions in 30-day windows
    yt_sorted = yt.sort_values("date").reset_index(drop=True)
    chops = []
    for i in range(len(yt_sorted) - 2):
        gap = (yt_sorted.iloc[i+2]["date"] - yt_sorted.iloc[i]["date"]).days
        if gap <= 30:
            chops.append((yt_sorted.iloc[i]["date"], yt_sorted.iloc[i+2]["date"]))
    # dedupe overlapping
    unique_chops = []
    if chops:
        unique_chops.append(chops[0])
        for c in chops[1:]:
            if c[0] > unique_chops[-1][1]:
                unique_chops.append(c)
    p(f"  (E) WHIPSAW / CHOP — clusters of 3+ transitions within 30 days: {len(unique_chops)}")
    for cstart, cend in unique_chops[:3]:
        cstr = (cstart.strftime('%Y-%m-%d'), cend.strftime('%Y-%m-%d'))
        ctr = trans[(trans["date"] >= cstart) & (trans["date"] <= cend)]
        p(f"        {cstr[0]} to {cstr[1]}: {len(ctr)} transitions in {(cend-cstart).days} days")
    p()

    # ---- Per-year verdict ----
    cost_A = sum(float(r['cost_pp']) for r in def_false) * 100
    cost_B = sum(float(r['cost_pp']) for r in risk_false) * 100
    cost_C = sum(float(r['cost_pp']) for r in late_reentry) * 100
    cost_D = ((mom_lag_wins["cum_m_pct"] - mom_lag_wins["winner_ret_pct"]).sum() * 100
              if len(mom_lag_wins) else 0)
    p(f"  ── DOMINANT CAUSE for {y} ──")
    p(f"    (A) False defensive cost:  {cost_A:+7.2f}pp")
    p(f"    (B) False risk-on cost:    {cost_B:+7.2f}pp")
    p(f"    (C) Late re-entry cost:    {cost_C:+7.2f}pp")
    p(f"    (D) Mom30 asset lag (in recovery windows): {cost_D:+7.2f}pp")
    p(f"    (E) Chop clusters:         {len(unique_chops)}")
    items = {"A-false-def": abs(cost_A), "B-false-on": abs(cost_B),
             "C-late-reentry": abs(cost_C), "D-mom30-lag": abs(cost_D)}
    if max(items.values()) > 0:
        dom = max(items, key=items.get)
        p(f"    → DOMINANT: {dom} (-{items[dom]:.2f}pp magnitude)")
    p()

# Cross-year summary
p("=" * 130)
p("  CROSS-YEAR SUMMARY — which failure modes dominate across all losing years?")
p("=" * 130)
p()
summary = []
for y in YEARS:
    yt = trans[trans["year"] == y]
    yw = windows[windows["year"] == y]
    def_false = [r for _, r in yt.iterrows() if "A-false-def" in r["modes"]]
    risk_false = [r for _, r in yt.iterrows() if "B-false-on" in r["modes"]]
    late_reentry = [r for _, r in yt.iterrows() if "C-late-reentry" in r["modes"]]
    mom_lag = yw[(yw["winner"] != "Mom30") &
                 ((yw["cum_m_pct"] - yw["winner_ret_pct"]) < -0.03)]
    cost_A = sum(float(r['cost_pp']) for r in def_false) * 100
    cost_B = sum(float(r['cost_pp']) for r in risk_false) * 100
    cost_C = sum(float(r['cost_pp']) for r in late_reentry) * 100
    cost_D = ((mom_lag["cum_m_pct"] - mom_lag["winner_ret_pct"]).sum() * 100
              if len(mom_lag) else 0)
    summary.append((y, cost_A, cost_B, cost_C, cost_D))

p(f"  {'Year':<6} {'(A) False def':>15} {'(B) False on':>14} {'(C) Late re-entry':>20} {'(D) Mom30 lag':>16}")
p("  " + "-"*6 + " " + "-"*15 + " " + "-"*14 + " " + "-"*20 + " " + "-"*16)
for y, a, b, c, d in summary:
    p(f"  {y:<6} {a:>+13.2f}pp {b:>+12.2f}pp {c:>+18.2f}pp {d:>+14.2f}pp")
p()
p("  Notes:")
p("    cost_A/B/C are 20-day forward NIFTY/Mom30 deviation × number of false transitions.")
p("    cost_D is the cumulative Mom30 vs winning-asset gap in recovery windows.")
p("    These costs OVERLAP — a single bad transition can contribute to multiple modes.")
p()

# Write output
txt = os.path.join(RESULTS_DIR, "diagnose_losing_years.txt")
with open(txt, "w") as f:
    f.write("\n".join(out))
print(f"\nSaved to {txt}")
